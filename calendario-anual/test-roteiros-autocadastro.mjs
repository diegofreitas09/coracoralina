import assert from 'node:assert/strict';
import {mock} from 'node:test';
const data=new Map();
const teacher={id:'test-teacher',name:'Docente Teste',email:'docente@example.test',profile:'Professor',segments:['Ensino Fundamental II'],status:'Ativo'};
mock.module('@netlify/blobs',{namedExports:{getStore:()=>({get:async key=>structuredClone(data.get(key)||null),setJSON:async(key,value)=>data.set(key,structuredClone(value))})}});
mock.module('../netlify/functions/lib/cora-team-auth.mjs',{namedExports:{listEmployees:async()=>({members:[teacher]})}});
const {roteiroAction}=await import('../netlify/functions/lib/cora-roteiros.mjs');
const call=(body,role='equipe',year=2027)=>{
 const url=new URL('https://escola.test/calendario-anual/api?action=roteiros&year='+year);
 return roteiroAction({role,member:role==='equipe'?teacher:null,url,request:new Request(url,{method:body?'POST':'GET',headers:{'x-cora-request':'portal'},...(body?{body:JSON.stringify(body)}:{})})});
};
assert.equal((await call({operation:'selfAssign',items:[{grade:'6º ano',subject:'INEXISTENTE'}]})).status,400);
assert.equal((await call({operation:'selfAssign',items:[{grade:'6º ano',subject:'GRAMÁTICA'},{grade:'1ª série',subject:'ARTE'}]})).ok,true);
let catalog=await call();
assert.equal(catalog.assignments.length,2);
assert.ok(catalog.templates.length>0);
assert.ok(catalog.templates.every(t=>t.subject==='GRAMÁTICA'||t.subject==='ARTE'));
assert.equal(catalog.documents.length,0,'Referência antiga não é envio no ano novo');
const model=catalog.templates.find(t=>t.grade==='6º ano'&&t.stage===1&&t.assessment==='AP2');
const submitted=await call({operation:'save',document:{...model,blocks:[{}],sourceText:model.rawText,confirmed:true,status:'enviado'}});
assert.equal(submitted.ok,true);
assert.equal(submitted.document.year,2027);
assert.equal(submitted.document.authorId,teacher.id);
const sent=await call(undefined,'gestao');
assert.equal(sent.documents[0].status,'enviado');
const schedule=[{date:'2027-03-02',grade:'6º ano',subject:'MATEMÁTICA',assessment:'AP2',stage:1},{date:'2027-03-02',grade:'6º ano',subject:'GRAMÁTICA',assessment:'AP2',stage:1}];
assert.equal((await call({operation:'schedule',items:schedule},'gestao')).ok,true);
assert.equal((await call(undefined,'gestao')).composite[0].subject,'MATEMÁTICA','Respeitar ordem escolhida pela Gestão, não ordem alfabética');
assert.equal((await call({operation:'review',authorId:teacher.id,documentId:submitted.document.id,revision:submitted.document.revision,status:'aprovado'},'gestao')).ok,true);
assert.equal((await call(undefined,'gestao')).composite[1].condition,'aprovado');
assert.equal((await call({operation:'selfAssign',items:[{grade:'6º ano',subject:'GRAMÁTICA'}]},'equipe',2028)).ok,true);
catalog=await call(undefined,'equipe',2028);
assert.equal(catalog.templates.find(t=>t.grade==='6º ano'&&t.stage===1&&t.assessment==='AP2').sourceYear,2027);
assert.equal(catalog.documents.length,0);
console.log('PASSOU: autocadastro, isolamento por conta/ano, modelo anterior, envio identificado, recebimento, ordenação e aprovação; armazenamento simulado.');
const multi={operation:'selfAssign',segments:['Ensino Fundamental II','Ensino Médio'],items:[{grade:'7º ano',subject:'CIÊNCIAS'},{grade:'8º ano',subject:'CIÊNCIAS'},{grade:'1ª série',subject:'BIOLOGIA'},{grade:'3ª série',subject:'BIOLOGIA'}]};
assert.equal((await call(multi)).ok,true);
const multiSaved=await call();
assert.deepEqual(multiSaved.profileSegments,multi.segments);
assert.equal(multiSaved.assignments.length,4);
assert.ok(multiSaved.templates.every(x=>multi.items.some(a=>a.grade===x.grade&&a.subject===x.subject)));
assert.equal((await call({...multi,segments:['Ensino Fundamental II']})).status,400);
assert.equal((await call({...multi,items:[{grade:'7º ano',subject:'BIOLOGIA'}]})).status,400);
assert.equal(multiSaved.types.segments['Ensino Médio'].length,3);
assert.equal(multiSaved.types.segments['Ensino Fundamental II'].length,4);
console.log('PASSOU: dois segmentos, múltiplas turmas, disciplinas distintas e rejeição de combinação incompatível.');
